import { describe, expect, it } from "vitest";
import { autoDateText, completeDateText } from "../dateTyping.js";

const year = String(new Date().getFullYear());

describe("autoDateText", () => {
  it.each([
    ["", ""],
    ["0", "0"],
    ["1", "1"],
    ["3", "3"],
    ["4", "04."],
    ["9", "09."],
    ["31", "31."],
    ["35", "03.05."],
    ["01", "01."],
    ["00", "0"],
    ["000", "0"],
    ["011", "01.1"],
    ["012", "01.02."],
    ["013", "01.03."],
    ["0101", "01.01."],
    ["01.2", "01.02."],
    ["01.1", "01.1"],
    ["01.13", "01.01.3"],
    ["01.00", "01.0"],
    ["010120", "01.01.20"],
    ["01012026", "01.01.2026"],
    ["010120261", "01.01.2026"],
    ["9102026", "09.10.2026"],
    ["1.1.2026", "01.01.2026"],
    ["1-1-2026", "01.01.2026"],
    ["1/1/2026", "01.01.2026"],
    ["1 1 2026", "01.01.2026"],
    ["1,1,2026", "01.01.2026"],
    ["1.", "01."],
    [".", ""],
    ["..", ""],
    ["01.01.2026.", "01.01.2026"],
    ["1.1.", "01.01."],
    ["ab1", "1"],
    ["2026-01-02", "02.01.2026"],
  ])("%j → %j", (raw, expected) => {
    expect(autoDateText(raw)).toBe(expected);
  });
});

describe("completeDateText", () => {
  it.each([
    ["01.01.2026", "01.01.2026"],
    ["1.1.2026", "01.01.2026"],
    ["01012026", "01.01.2026"],
    ["9102026", "09.10.2026"],
    ["2026-01-02", "02.01.2026"],
    ["0101", `01.01.${year}`],
    ["1.1", `01.01.${year}`],
    ["1.1.", `01.01.${year}`],
    ["01.01.26", "01.01.2026"],
    ["1.1.26", "01.01.2026"],
    ["", ""],
    ["abc", ""],
    ["15", ""],
    ["15.", ""],
    ["00.01.2026", ""],
    ["01.00.2026", ""],
    ["1.1.2", ""],
    ["1.1.202", ""],
  ])("%j → %j", (raw, expected) => {
    expect(completeDateText(raw)).toBe(expected);
  });
});
